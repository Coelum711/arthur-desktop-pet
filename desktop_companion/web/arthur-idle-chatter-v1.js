  // Lunar New Year days (Gregorian) for the next few years.
  const LUNAR_NEW_YEAR = {2026:'02-17', 2027:'02-06', 2028:'01-26', 2029:'02-13', 2030:'02-03', 2031:'01-23'};

  function partOfDay(hour) {
    if (hour >= 23 || hour < 5) return 'night';
    if (hour < 11) return 'morning';
    if (hour < 17) return 'afternoon';
    return 'evening';
  }

  function season(month) {   // 0-based month
    if (month === 11 || month <= 1) return 'winter';
    if (month <= 4) return 'spring';
    if (month <= 7) return 'summer';
    return 'autumn';
  }

  // Gregorian Easter Sunday (anonymous algorithm).
  function easter(year) {
    const a = year % 19, b = Math.floor(year / 100), c = year % 100;
    const d = Math.floor(b / 4), e = b % 4, f = Math.floor((b + 8) / 25);
    const g = Math.floor((b - f + 1) / 3), h = (19 * a + b - d - g + 15) % 30;
    const i = Math.floor(c / 4), k = c % 4, l = (32 + 2 * e + 2 * i - h - k) % 7;
    const m = Math.floor((a + 11 * h + 22 * l) / 451);
    const month = Math.floor((h + l - 7 * m + 114) / 31), day = ((h + l - 7 * m + 114) % 31) + 1;
    return new Date(year, month - 1, day);
  }
  const sameDay = (x, y) => x.getFullYear() === y.getFullYear() && x.getMonth() === y.getMonth() && x.getDate() === y.getDate();
  const shift = (date, days) => new Date(date.getFullYear(), date.getMonth(), date.getDate() + days);
  // The nth given weekday of a month (n = -1 for the last one).
  function nthWeekday(year, month0, weekday, n) {
    if (n > 0) {
      const first = new Date(year, month0, 1);
      return new Date(year, month0, 1 + ((weekday - first.getDay() + 7) % 7) + (n - 1) * 7);
    }
    const last = new Date(year, month0 + 1, 0);
    return new Date(year, month0, last.getDate() - ((last.getDay() - weekday + 7) % 7));
  }

  function holiday(now) {
    const m = now.getMonth() + 1, d = now.getDate(), y = now.getFullYear();
    const md = `${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
    const e = easter(y);
    if (sameDay(now, shift(e, -47))) return 'pancake';
    if (sameDay(now, shift(e, -21))) return 'mothering';
    if (md === '11-11' || sameDay(now, nthWeekday(y, 10, 0, 2))) return 'remembrance';
    if (md === '12-26') return 'boxing';
    if (md === '03-01') return 'stdavid';
    if (md === '03-17') return 'stpatrick';
    if (md === '11-30') return 'standrew';
    if (md === '01-25') return 'burns';
    if (md === '05-29') return 'oakapple';
    if (sameDay(now, nthWeekday(y, 5, 6, 2))) return 'trooping';
    if (sameDay(now, nthWeekday(y, 8, 6, 2))) return 'proms';
    if (sameDay(now, nthWeekday(y, 4, 1, -1))) return 'cheese';
    { // Wimbledon: the fortnight starting five weeks before the first Monday of August
      // (2025: 30 Jun, 2026: 29 Jun, 2027: 28 Jun).
      const start = shift(nthWeekday(y, 7, 1, 1), -35);
      const diff = (now - start) / 86400000;
      if (diff >= 0 && diff < 14) return 'wimbledon';
    }
    if (m === 12 && d >= 20 && d <= 25) return 'christmas';
    if ((m === 12 && d >= 30) || (m === 1 && d <= 2)) return 'newyear';
    if (md === '11-05') return 'bonfire';
    if (md === '10-31') return 'halloween';
    if (md === '02-14') return 'valentine';
    if (md === '04-23') return 'stgeorge';
    const lny = LUNAR_NEW_YEAR[now.getFullYear()];
    if (lny) {
      const [lm, ld] = lny.split('-').map(Number);
      const start = new Date(now.getFullYear(), lm - 1, ld);
      const diff = (now - start) / 86400000;
      if (diff >= -1 && diff < 3) return 'lunarnewyear';
    }
    return null;
  }

